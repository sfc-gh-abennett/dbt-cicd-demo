-- =====================================================================
-- dbt CI/CD demo: Snowflake environment setup
-- Run once as ACCOUNTADMIN (or SYSADMIN + USERADMIN + SECURITYADMIN).
-- Creates: 1 warehouse, 3 databases, 3 env roles, 2 service users
--   SVC_DBT_GITHUB  -> used by GitHub Actions (CI to TEST, CD to PROD)
--   SVC_DBT_CLOUD   -> used by dbt Cloud environments
-- =====================================================================

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS DBT_DEMO_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS DBT_DEMO_DEV;
CREATE DATABASE IF NOT EXISTS DBT_DEMO_TEST;
CREATE DATABASE IF NOT EXISTS DBT_DEMO_PROD;

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS DBT_DEMO_DEV_ROLE;
CREATE ROLE IF NOT EXISTS DBT_DEMO_TEST_ROLE;
CREATE ROLE IF NOT EXISTS DBT_DEMO_PROD_ROLE;
GRANT ROLE DBT_DEMO_DEV_ROLE  TO ROLE SYSADMIN;
GRANT ROLE DBT_DEMO_TEST_ROLE TO ROLE SYSADMIN;
GRANT ROLE DBT_DEMO_PROD_ROLE TO ROLE SYSADMIN;

-- Each role: use the warehouse, own its own database, read sample data.
GRANT USAGE ON WAREHOUSE DBT_DEMO_WH TO ROLE DBT_DEMO_DEV_ROLE;
GRANT USAGE ON WAREHOUSE DBT_DEMO_WH TO ROLE DBT_DEMO_TEST_ROLE;
GRANT USAGE ON WAREHOUSE DBT_DEMO_WH TO ROLE DBT_DEMO_PROD_ROLE;

GRANT ALL ON DATABASE DBT_DEMO_DEV  TO ROLE DBT_DEMO_DEV_ROLE;
GRANT ALL ON DATABASE DBT_DEMO_TEST TO ROLE DBT_DEMO_TEST_ROLE;
GRANT ALL ON DATABASE DBT_DEMO_PROD TO ROLE DBT_DEMO_PROD_ROLE;

GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DBT_DEMO_DEV_ROLE;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DBT_DEMO_TEST_ROLE;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DBT_DEMO_PROD_ROLE;

-- Prod is read-only for the dev role, which makes "dev vs prod" separation easy to show.
GRANT USAGE ON DATABASE DBT_DEMO_PROD TO ROLE DBT_DEMO_DEV_ROLE;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE DBT_DEMO_PROD TO ROLE DBT_DEMO_DEV_ROLE;
GRANT SELECT ON FUTURE TABLES IN DATABASE DBT_DEMO_PROD TO ROLE DBT_DEMO_DEV_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN DATABASE DBT_DEMO_PROD TO ROLE DBT_DEMO_DEV_ROLE;

